def contains_forbidden(text: str) -> bool:
    """텍스트에 금지 표현이 하나라도 포함되어 있으면 True를 반환합니다."""
    return any(phrase in text for phrase in FORBIDDEN_PHRASES)


def find_violations(text: str) -> list[str]:
    """텍스트에서 발견된 모든 금지 표현 목록을 반환합니다."""
    return [phrase for phrase in FORBIDDEN_PHRASES if phrase in text]


def sanitize(text: str) -> str:
    """금지 표현을 안전한 대체 표현으로 치환합니다.
    대체 표현이 빈 문자열인 경우 해당 표현을 제거합니다.
    LLM 재생성 3회 모두 실패 시 템플릿 강제 출력 전 전처리 용도로 사용합니다.
    """
    result = text
    for phrase, alternative in SAFE_ALTERNATIVES.items():
        result = result.replace(phrase, alternative)
    return result
